"""Recover rod fishing's actual species/frame/hitbox assignments from data.x.c()."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def recover():
    source=(ROOT/'evidence/decompiled/data/x.java').read_text()
    method=source[source.index('public final void c()'):source.index('public final void d()')]
    profiles=[]
    for body in re.split(r'case \d+: \{',method)[1:]:
        item=int(re.search(r'this.n = (\d+);',body)[1])
        right=[int(x) for x in re.findall(r'this.e\[\d\] = (\d+);',body)]
        left=[int(x) for x in re.findall(r'this.f\[\d\] = (\d+);',body)]
        w=int(re.search(r'this.o = (\d+);',body)[1]);h=int(re.search(r'this.p = (\d+);',body)[1])
        assert len(right)==len(left)==3
        profiles.append({'item':item,'right':right,'left':left,'width':w,'height':h})
    assert [p['item'] for p in profiles]==[40,56,57,58]
    for marker in ['this.a.m[n2] == 90','this.i -= 3','this.j -= 3','this.j + 3 + 17','this.d = new int[5]','this.a.n[14]','this.a.m[14]','this.g < -((data.k.b() >> 1) - 37 - data.k.b() / 11)']:
        assert marker in source,marker
    action=(ROOT/'evidence/decompiled/data/a.java').read_text()
    assert 'this.a.k[this.a.P + 180] == 5' in action and 'this.c(40)' in action
    rules={'source':'data.x.a/b/c/g/h/j; data.a.c-f/c(int); data.v.b; javap data.p/x/v',
      'width':240,'height':320,'tickMs':90,'terrain':5,'tool':14,'bait':90,
      'moveStep':3,'hookOffset':20,'historySlots':5,'fishStep':1,'escapeStep':1,
      'floatSprite':851979,'hookFrames':[851980,851981],'toolSprite':851976,'fish':profiles}
    data=json.dumps(rules,indent=2)
    (ROOT/'evidence/rod-fishing-rules.json').write_text(data+'\n')
    (ROOT/'src/game/data/rodFishingRules.ts').write_text('// Generated by tools/recover_rod_fishing.py. 240x320 is a browser reference viewport.\nexport const rodFishingRules = '+data+' as const;\n')
    print('Recovered all four rod-fishing species, hitboxes and sprite references.')
if __name__=='__main__':recover()

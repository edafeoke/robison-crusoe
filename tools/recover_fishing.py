"""Audit and export data.x's net-fishing rules; do not rewrite original assets."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def recover():
    source=(ROOT/'evidence/decompiled/data/x.java').read_text()
    method=source[source.index('private void c(int n2)'):source.index('private void o()')]
    frames=[int(v) for v in re.findall(r'this\.[ab]\[n2\]\[\d\] = (\d+);',method)]
    assert len(frames)==60
    profiles=[]
    for i,threshold in enumerate([45,65,75,85,100]):
        a=frames[i*12:(i+1)*12]
        assert a[:3]==a[9:12] and a[3:6]==a[6:9]
        profiles.append({'below':threshold,'right':a[:3],'left':a[3:6]})
    for s in ['this.a.m[n2] == 26','this.D >= 10','this.B == 5','this.A = 32','this.z = 16','this.x += 5','this.a.n[83]','this.a.m[83]','by = 59;','by = 60;','by = 2;']:
        assert s in source,s
    action=(ROOT/'evidence/decompiled/data/a.java').read_text()
    assert 'this.a.k[this.a.P + 180] == 4' in action and 'this.c(59)' in action
    rules={'source':'data.x.d/e/f/k/l/m/n/c(int), data.a.g-j/c(int); javap data.x',
      'width':240,'height':320,'tickMs':90,'terrain':4,'tool':83,'bait':26,
      'target':10,'maxCasts':5,'netWidth':32,'netHeight':16,'netStep':5,'haulMs':2000,
      'spawnMin':3,'spawnRange':5,'speedMin':2,'speedRange':3,'offscreen':70,
      'netSprite':851984,'toolSprite':851986,'rewardItems':[59,60,2],'fish':profiles}
    data=json.dumps(rules,indent=2)+'\n'
    (ROOT/'evidence/net-fishing-rules.json').write_text(data)
    (ROOT/'src/game/data/netFishingRules.ts').write_text('// Generated by tools/recover_fishing.py. 240x320 is a browser reference viewport.\nexport const netFishingRules = '+data.rstrip()+' as const;\n')
    print('Recovered net-fishing frames, source rules and uncorrected reward IDs.')
if __name__=='__main__':recover()

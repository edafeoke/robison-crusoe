"""Recover world USE food eligibility and verify ad.j separately from satchel ad.g/h."""
from pathlib import Path
import json
import re
ROOT = Path(__file__).resolve().parents[1]

def recover():
    actions = (ROOT / 'evidence/decompiled/data/a.java').read_text()
    menu = actions[actions.index('private void c(int n2)'):actions.index('private void u()')]
    assert menu.index('this.a.d[n2] != -1') < menu.index('this.a.c[n2] != -1')
    assert 'this.a.c[n2] == 0' in menu and 'this.D();' in menu
    assert 'this.a.t[this.a.C] = 655387;' in actions
    source = (ROOT / 'evidence/decompiled/data/ad.java').read_text()
    body = source[source.index('public final void j()'):source.index('public final void b(int n2)')]
    assert 'this.a.c[n7] != 0 || this.a.c[n7] != -1' in body  # Always true, not AND.
    assert body.count('this.a.c = (float)n4') == 2
    assert len(re.findall(r'this.b\(\);\s*return;', body)) == 2
    assert body.index('this.a.a.a(this.a.j[n7]);') > body.rindex('this.b();')
    assert 'this.h();' not in body  # No tool-stack consumption or coconut opening counter.
    bytecode = (ROOT / 'evidence/bytecode/data.ad.txt').read_text()
    method = bytecode[bytecode.index('public final void j();'):bytecode.index('public final void b(int);')]
    assert len(re.findall(r'putfield[^\n]*// Field data/p.c:F', method)) == 2
    assert 'Field data/p.c:F' in method and method.count('Method data/v.a:(I)V') == 1
    items = json.loads((ROOT / 'public/assets/objects/objects.json').read_text())
    profiles = [{'item': i['id'], 'mapId': i['mapId'], 'tool': i['interaction']['useTool'] or None}
                for i in items if i['category'] == 0 and i['interaction']['huntingTool'] == -1 and i['interaction']['useTool'] >= 0]
    assert len(profiles) == 22
    rules = {'source': 'data.a.c/D world USE -> data.ad.j; independent of ad.g/h',
             'energyPasses': 2, 'toolWear': False, 'nutritionAfterEnergyChecks': True,
             'profiles': profiles}
    data = json.dumps(rules, indent=2)
    (ROOT / 'evidence/world-food-rules.json').write_text(data + '\n')
    (ROOT / 'src/game/data/worldFoodRules.ts').write_text('// Generated by tools/recover_world_food.py. Original world USE rules.\nexport const worldFoodRules = ' + data + ' as const;\n')
    print('Recovered 22 static world foods, double energy and early fatal-return ordering.')

if __name__ == '__main__':
    recover()

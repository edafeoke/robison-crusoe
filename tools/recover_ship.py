"""Recover pirate-ship reconstruction/ending and retain separate raft navigation findings."""
from pathlib import Path
import json
import re
ROOT = Path(__file__).resolve().parents[1]

def recover():
    a = (ROOT / 'evidence/decompiled/data/a.java').read_text()
    body = a[a.index('private void G()'):a.index('public final void p()')]
    ship = next(m for m in re.finditer(r'else if \(this.a.ao == (\d+)\) \{\s*this.a.f\[(\d+)\] = this.a.f\[(\d+)\];(.*?)(?=else if)', body, re.S) if 'this.a.aF = true;' in m[4])
    repair, wreck, copy = map(int, ship.group(1,2,3))
    assert repair == copy == 19 and wreck == 18
    assert 'this.a.ac -= 2;' in ship[4] and 'this.a.aF = true;' in ship[4]
    assert 'this.a.a.l();' in ship[4] and 'this.a.a.o();' in body
    v = (ROOT / 'evidence/decompiled/data/v.java').read_text()
    delay = int(re.search(r'this.a.aF && this.a.H > (\d+)L', v)[1])
    assert 'this.a.l = 9;' in v and 'this.a.a.a(97)' in v and 'this.a.a.a(98)' in v
    c = (ROOT / 'evidence/decompiled/data/c.java').read_text().split('public final void c()')[1]
    flags = list(map(int, re.findall(r'this.a\[0\] = (\d+);', c)))
    assert flags == [393222,393223]
    flag_ms = int(re.search(r'this.a.w > (\d+)L', c)[1])
    y = (ROOT / 'evidence/decompiled/data/y.java').read_text()
    def offsets(key):
        start = y.index(f'this.a.f[this.a.l[n5 + n4 * 180] - 1] == {key}')
        block = y[start:y.index('\n                        }', start)]
        pairs = re.findall(r'this.a.a.a\(\(\(k\)this.a\).a, this.a.a.a\[0\], (.*?), (.*?)\);',block)
        def value(expression):
            for field, replacement in [('this.a.aM','0'),('this.a.aN','0'),('this.a.M','16'),('this.a.U','0'),('this.a.V','0'),('n2','0'),('n3','0')]:
                expression=expression.replace(field,replacement)
            assert re.fullmatch(r'[0-9 +*/()-]+',expression), expression
            return int(eval(expression.replace('/','//'),{'__builtins__':{}}))+8  # source tile-centre baseline is -8
        result=[{'dx':value(x),'dy':value(y)} for x,y in pairs]
        assert len(result)==2
        return result
    items=json.loads((ROOT/'public/assets/objects/objects.json').read_text())
    g=(ROOT/'evidence/decompiled/data/g.java').read_text()
    water=g[g.index('public final boolean b(int n2, int n3)'):g.index('public final boolean c(int n2, int n3)')]
    for tile in [12,13,14]:
        assert f'this.a.e[{tile}] = {tile};' in g and f'this.a.e[{tile}]' in water
    island=json.loads((ROOT/'public/assets/maps/island.json').read_text())
    locations=[i for i,value in enumerate(island['layers']['Objects']) if value==wreck+1]
    assert len(locations)==1
    sail=items[repair]['recipe'][0]['item']
    assert items[sail]['name']=='Large sail' and items[sail]['sprite']==-1
    assert items[repair]['shelterRequirement']==wreck
    rules={'source':'data.a.c/z/G, data.r.a, data.ad.l/o, data.v.b/d, data.y, data.c.c',
           'wreckItem':wreck,'repairItem':repair,'mapId':wreck+1,'index':locations[0],
           'sailItem':sail,'wreckSprite':items[wreck]['sprite'],'repairedSprite':items[repair]['sprite'],
           'strictDepartureMs':delay,'northShiftTiles':2,'winText':97,'endingText':98,
           'flagMs':flag_ms,'flagFrames':flags,'wreckFlags':offsets(items[wreck]['sprite']),
           'repairedFlags':offsets(items[repair]['sprite'])}
    atlas=json.loads((ROOT/'public/assets/ui/atlas.json').read_text())
    for key in flags+[rules['wreckSprite'],rules['repairedSprite']]: assert atlas['sheets'][key>>16]['frames'][key&65535]
    data=json.dumps(rules,indent=2)
    (ROOT/'src/game/data/shipRules.ts').write_text('// Generated by tools/recover_ship.py. Original reconstruction and ending facts.\nexport const shipRules = '+data+' as const;\n')
    raft={'source':'data.a.G; data.ad.u/v; data.g.b(int,int)/n; data.ab.b/k; data.t',
          'brokenItem':84,'repairedItem':94,'originalCell':island['layers']['Objects'].index(85),
          'waterTerrain':[12,13,14],'recipe':items[94]['recipe'],'tools':items[94]['craftingTools'],
          'implemented':False}
    (ROOT/'evidence/ship-and-raft-rules.json').write_text(json.dumps({'ship':rules,'raftAudit':raft},indent=2)+'\n')
    print('Recovered ship reconstruction/8-second ending, both flag anchors and separate raft rules.')

if __name__=='__main__': recover()

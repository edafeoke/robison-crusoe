"""Recover nutrition/body-weight arithmetic, without inventing item mass or encumbrance."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]

def recover():
    source = (ROOT / 'evidence/decompiled/data/v.java').read_text()
    body = source[source.index('public final void a(int n2)'):source.index('public final void f()')]
    assert 'this.a.L += n2;' in body
    threshold = int(re.search(r'this.a.L >= (\d+)', body)[1])
    assert f'this.a.L -= {threshold};' in body
    step = int(re.search(r'this.a.g \+= (\d+).0f;', body)[1])
    assert 'if (this.a.g < this.a.d)' in body and 'while' not in body
    player = (ROOT / 'evidence/decompiled/data/p.java').read_text()
    divisor, margin = map(int, re.search(r'this.b = this.a = \(float\)\(\(data.k.a\(\) / (\d+) - (\d+)\) / 1\);', player).groups())
    assert (divisor, margin) == (3, 16)
    assert 'this.d = this.a;' in player
    bytecode = (ROOT / 'evidence/bytecode/data.v.txt').read_text()
    method = bytecode[bytecode.index('public final void a(int);'):bytecode.index('public final void f();')]
    for field in ['data/p.L:I', 'data/p.g:F', 'data/p.d:F']:
        assert field in method
    inventory = (ROOT / 'evidence/bytecode/data.ad.txt').read_text()
    assert inventory.count('Method data/v.a:(I)V') == 3  # g twice, direct-world j once
    texts = json.loads((ROOT / 'public/assets/ui/story.json').read_text())
    assert texts[75] == 'Weight'
    rules = {'source': 'data.v.a(int), data.p.c, data.ad.g/j, data.aa stats, data.t save/load',
             'nutritionThreshold': threshold, 'barStep': step,
             'barWidthDivisor': divisor, 'barWidthMargin': margin,
             'labelText': 75, 'browserReferenceWidth': 240}
    data = json.dumps(rules, indent=2)
    (ROOT / 'evidence/body-weight-rules.json').write_text(data + '\n')
    (ROOT / 'src/game/data/bodyWeightRules.ts').write_text('// Generated by tools/recover_weight.py. Reference width is an explicit browser choice.\nexport const bodyWeightRules = ' + data + ' as const;\n')
    print('Recovered nutrition-driven body-weight rules; no carrying-mass gate inferred.')

if __name__ == '__main__':
    recover()

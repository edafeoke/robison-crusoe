"""Recover world contact rules independently of the hunting minigame."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]

def recover():
    source = (ROOT / 'evidence/decompiled/data/d.java').read_text()
    contact = source[source.index('if (this.c > 1000L)'):source.index('public final void a(int')]
    costs = {}
    for cases, cost in re.findall(r'((?:case \d+:\s*)+)\{\s*this\.a\.c -= this\.a\.d / 100\.0f \* (\d+)\.0f;', contact):
        for key in re.findall(r'case (\d+):', cases):
            costs[int(key)] = int(cost)
    protected = source[source.index('public final boolean a()'):]
    rules = []
    for key, field, cost in re.findall(r'case (\d+): \{\s*if \(this\.a\.([abcd])\[this\.a\.[DEFG]\] != -1\) \{\s*this\.a\.c -= this\.a\.d / 100\.0f \* (\d+)\.0f;', protected):
        key = int(key)
        rules.append({'mapId': key, 'kind': 'timed', 'energy': costs[key],
                      'slot': {'a': 'hat', 'b': 'shirt', 'c': 'pants', 'd': 'shoes'}[field],
                      'protectedEnergy': int(cost)})
    assert [r['mapId'] for r in rules] == [43, 44, 49, 50]
    assert 'Math.abs(this.c - this.a.Z) <= 1 && Math.abs(this.d - this.a.aa) <= 1' in source
    assert 'this.a.q * 30 / 10000' in contact
    shark = (ROOT / 'evidence/decompiled/data/i.java').read_text()
    assert re.search(r'Math.abs\(this.a - this.a.Z\) <= 1 && Math.abs\(this.b - this.a.aa\) <= 1\) \{\s*this.a.c = 0.0f;\s*this.a.aO = true;', shark)
    constructors = (ROOT / 'evidence/decompiled/data/g.java').read_text()
    for rule in rules + [{'mapId': 56}]:
        block = constructors[constructors.index(f"case {rule['mapId']}: {{", constructors.index('int n19 = 0;')):]
        assert f"new {'i' if rule['mapId'] == 56 else 'd'}(" in block[:block.index('\n                }')]
    rules.append({'mapId': 56, 'kind': 'instant', 'energy': 100, 'slot': None, 'protectedEnergy': None})
    result = {'source': 'data.d.a update/protection; data.i.a update; data.g constructors',
              'radiusTiles': 1, 'strictDelayMs': 1000, 'contacts': rules}
    data = json.dumps(result, indent=2)
    (ROOT / 'evidence/world-hazard-rules.json').write_text(data + '\n')
    (ROOT / 'src/game/data/worldHazardRules.ts').write_text('// Generated by tools/recover_hazards.py. World contacts, not hunting triggers.\nexport const worldHazardRules = ' + data + ' as const;\n')
    print('Recovered four timed predator contacts and immediate shark contact.')

if __name__ == '__main__':
    recover()

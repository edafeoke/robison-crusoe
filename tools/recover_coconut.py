"""Recover n's action references and x's constructor tables, including a CFR omission."""
import json, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def recover():
    bytecode=(ROOT/'evidence/bytecode/data.x.txt').read_text()
    ctor=bytecode[bytecode.index('public data.x(data.p);'):]
    arrays={}
    for body,name in re.findall(r'newarray\s+int(.*?)putfield\s+#\d+\s+// Field ([ab]):\[I',ctor,re.S):
        stack=[]; values={}
        for op,arg in re.findall(r'^[ \t]*\d+:[ \t]+(iconst_\w+|bipush|sipush|iastore)[ \t]*([^\n]*)',body,re.M):
            if op=='iastore':
                value=stack.pop(); index=stack.pop(); values[index]=value
            elif op.startswith('iconst_'): stack.append(-1 if op=='iconst_m1' else int(op[7:]))
            else: stack.append(int(arg.strip()))
        assert len(values)==16 and set(values)==set(range(16))
        arrays[name]=[values[i] for i in range(16)]
        if len(arrays)==2:break
    assert set(arrays)=={'a','b'}
    source=(ROOT/'evidence/decompiled/data/n.java').read_text()
    for evidence in ['this.h < 5','this.i == 10','> 11000L','this.e[n4] + 5','this.a.q[n6] + 1']:
        # The fall step uses n4; the source statement is retained verbatim in evidence.
        if evidence=='this.e[n4] + 5': assert 'this.e[n4] = this.e[n4] + 5' in source
        else: assert evidence in source,evidence
    rules={'source':'data.n; data.x constructor (javap); data.a; data.g/h; data.t',
           'tickMs':90,'width':240,'height':320,'target':5,'maxThrows':10,
           'shakeMs':11000,'fallStep':5,'angleMin':10,'angleMax':70,'angleStep':5,
           'powerMin':40,'powerMax':100,'powerStep':2,'sine':arrays['a'],'cosine':arrays['b'],
           'sprites':{'coconut':851970,'stone':851985,'leaves':[458805,458806,458807]},
           'palmDecor':18,'palmVariant':8}
    (ROOT/'evidence/coconut-rules.json').write_text(json.dumps(rules,indent=2)+'\n')
    path=ROOT/'src/game/data/coconutRules.ts';path.parent.mkdir(exist_ok=True)
    path.write_text('// Generated by tools/recover_coconut.py. Source dimensions are a browser reference viewport.\nexport const coconutRules = '+json.dumps(rules,indent=2)+' as const;\n')
    print('Recovered coconut challenge constants and both bytecode trajectory tables.')
if __name__=='__main__':recover()

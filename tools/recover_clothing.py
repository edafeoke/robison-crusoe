"""Recover ab.j outfit layers and constructor hat motion omitted by CFR; s protection."""
from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[1]
def recover():
    source=(ROOT/'evidence/decompiled/data/ab.java').read_text()
    method=source[source.index('private void j()'):source.index('public final void b()')]
    items=json.loads((ROOT/'public/assets/objects/objects.json').read_text())
    slots={0:'hat',1:'shirt',2:'shoes',3:'pants'}
    profiles=[]
    for item,body in re.findall(r'case (\d+): \{(.*?)(?=\n            case |\n        \})',method,re.S):
        item=int(item)
        keys=[int(k) for k in re.findall(r'this\.a\.a\.a\(\(\(k\)this\.a\)\.a, (\d+)',body)]
        assert len(keys)==4,(item,keys)
        slot=slots[int(items[item]['rawFields'][11])]
        assert {7:'shirt',8:'pants',9:'shoes',10:'hat'}[items[item]['category']] == slot
        profiles.append({'item':item,'slot':slot,'sequences':dict(zip(['up','down','left','right'],keys)),'frames':1 if slot=='hat' else 5})
    assert sorted(p['item'] for p in profiles)==list(range(99,115))
    bytecode=(ROOT/'evidence/bytecode/data.ab.txt').read_text()
    ctor=bytecode[bytecode.index('public data.ab(data.p);'):]
    arrays={}
    for body,name in re.findall(r'newarray\s+int(.*?)putfield\s+#\d+\s+// Field ([a-h]):\[I',ctor,re.S):
        stack=[];values={}
        for op,arg in re.findall(r'^[ \t]*\d+:[ \t]+(iconst_\w+|bipush|sipush|iastore)[ \t]*([^\n]*)',body,re.M):
            if op=='iastore':
                value=stack.pop();index=stack.pop();values[index]=value
            elif op.startswith('iconst_'):stack.append(-1 if op=='iconst_m1' else int(op[7:]))
            else:stack.append(int(arg.strip()))
        assert set(values)==set(range(5))
        arrays[name]=[values[i] for i in range(5)]
        if len(arrays)==8:break
    assert set(arrays)==set('abcdefgh')
    hunt=(ROOT/'evidence/decompiled/data/s.java').read_text()
    protection=[]
    for item,body in re.findall(r'case (\d+): \{(.*?)(?=\n                            case |\n                        \})',hunt,re.S):
        check=re.search(r'if \(this\.a\.([abcd])\[this\.a\.([DEFG])\] != -1\)',body)
        if not check:continue
        costs=[int(v) for v in re.findall(r'100\.0f \* (\d+)\.0f',body)]
        assert len(costs)==2
        protection.append({'item':int(item),'slot':{'a':'hat','b':'shirt','c':'pants','d':'shoes'}[check[1]],'protected':costs[0],'unprotected':costs[1]})
    assert [p['item'] for p in protection]==[42,43,48,49]
    atlas=json.loads((ROOT/'public/assets/ui/atlas.json').read_text())
    for p in profiles:
        for key in p['sequences'].values():
            assert all(atlas['sheets'][key>>16]['frames'][((key&65535)+i)] for i in range(p['frames']))
    rules={'source':'data.ab.j, javap ab constructor; data.y/ad/a/aa/t; data.s retaliation','layerOrder':['shoes','pants','shirt','hat'],
      'hatOffsets':{direction:{'x':arrays[x],'y':arrays[y]} for direction,x,y in [('down','a','b'),('up','c','d'),('left','e','f'),('right','g','h')]},
      'profiles':sorted(profiles,key=lambda p:p['item']),'protection':protection}
    data=json.dumps(rules,indent=2)
    (ROOT/'evidence/clothing-rules.json').write_text(data+'\n')
    (ROOT/'src/game/data/clothingRules.ts').write_text('// Generated by tools/recover_clothing.py. Packed source frames, no rearranged sheets.\nexport const clothingRules = '+data+' as const;\n')
    print('Recovered all 16 clothing profiles, 8 bytecode hat-offset arrays and 4 protection rules.')
if __name__=='__main__':recover()

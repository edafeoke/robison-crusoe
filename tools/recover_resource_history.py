"""Source-bounded supply removal history; no invented spawn rates or recipe quantities."""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[1]
def recover():
    ad=(ROOT/'evidence/decompiled/data/ad.java').read_text();g=(ROOT/'evidence/decompiled/data/g.java').read_text();y=(ROOT/'evidence/decompiled/data/y.java').read_text()
    recent=ad[ad.index('private void c(int n2)'):ad.index('private void w()')]
    permanent=ad[ad.index('public final void a(int n2)'):ad.index('public final void c()')]
    recentCap=int(re.search(r'this.a.aD == (\d+)',recent)[1]);permanentCap=int(re.search(r'this.a.aC == (\d+)',permanent)[1])
    assert recentCap==20 and permanentCap==70
    pickup=ad[ad.index('public final void a()'):ad.index('public final void b()')]
    ids=list(map(int,re.search(r'this.a.al == (\d+) \|\| this.a.al == (\d+) \|\| this.a.al == (\d+)',pickup).groups()))
    assert ids==[93,21,38] and 'this.c(this.a.P + 180)' in pickup
    unique=[int(v) for _,v in re.findall(r'this.a\[(\d+)\] = (\d+);',g[g.index('public final void c()'):g.index('private void k()')])]
    assert len(unique)==49 and 13 not in unique and 14 not in unique and 77 in unique
    mobile=y[y.index('public final boolean a(int n2)'):y.index('public final void b()')]
    assert 'n2 == 3' in mobile and 'n2 == 5' in mobile
    mobileIds=[3,5]+[n for a,b in re.findall(r'n2 >= (\d+) && n2 <= (\d+)',mobile) for n in range(int(a),int(b)+1)]
    assert len(mobileIds)==22
    assert 'this.a.K == 4L && !this.c' in ad and 'this.w();' in ad[ad.index('public final void s()'):ad.index('public final void t()')]
    for token in ['this.l();','this.n();','this.m();']: assert token in g[g.index('public final void d()'):g.index('public final void e()')]
    j=ad[ad.index('public final void j()'):ad.index('public final void b(int n2)')];assert 'this.c(' not in j and 'this.a.l[this.a.P + 180] = 0;' in j
    result={'source':'data.ad.a/c/a(int)/s; data.g.k/l/m/d/a(boolean); data.y.a; JVM p.s:[I,p.r:[I,p.a:[S',
      'recentCapacity':recentCap,'permanentCapacity':permanentCap,'minedItems':ids,'uniqueMapIds':unique,'mobileMapIds':mobileIds,'dailyResetHour':4}
    (ROOT/'src/game/data/resourceHistoryRules.ts').write_text('// Generated by tools/recover_resource_history.py. Original bounded pickup histories.\nexport const resourceHistoryRules = '+json.dumps(result,indent=2)+' as const;\n')
    (ROOT/'evidence/resource-history-rules.json').write_text(json.dumps(result,indent=2)+'\n')
    print('Recovered 20/70 pickup histories, 49 carried-unique filters, mobile exclusions and 04:00 reset.')
if __name__=='__main__': recover()

"""Recover swamp-raft collision, transition and ordered rendering evidence."""
from pathlib import Path
import json, re
ROOT=Path(__file__).resolve().parents[1]
def recover():
    def source(name): return (ROOT/f'evidence/decompiled/data/{name}.java').read_text()
    a,ad,ab,g=map(source,['a','ad','ab','g'])
    repair=a[a.index('} else if (this.a.ao == 94)'):a.index('} else if (this.a.f[this.a.ao] == 1)')]
    assert 'this.a.ap = 1;' in repair and 'this.a.l[n2] == 85' in repair and 'this.a.l[n2] = 95;' in repair
    board=ad[ad.index('public final void u()'):ad.index('public final void v()')]
    assert 'this.a.T = true;' in board and 'this.a.f[94] == 393224' in board
    assert len(re.findall(r'this.a.a.[abcd]\(4\)',board))==4
    # The argument is unused! These calls start a single grid step with p.aj pixels per tick.
    for method,nextmethod in [('a','b'),('b','c'),('c','d')]:
        movement=ab[ab.index(f'public final void {method}(int n2)'):ab.index(f'public final void {nextmethod}(int n2)')]
        assert movement.count('n2')==1 and 'this.a.aj' in movement and 'this.a.M' in movement
    assert 'this.aj = this.M / 2;' in source('p')
    land=a[a.index('private boolean b()'):a.index('private boolean c()')]
    assert land.count('this.a.a.a(')==8 and 'this.a.a.e(' not in land # duplicate terrain, no rocks
    bytecode=(ROOT/'evidence/bytecode/data.a.txt').read_text().split('private boolean b();')[1].split('private boolean c();')[0]
    assert bytecode.count('Method data/g.a:(II)Z')==8 and 'Method data/g.e:(II)Z' not in bytecode
    water=g[g.index('public final boolean b(int n2, int n3)'):g.index('public final boolean c(int n2, int n3)')]
    terrain=[int(x) for x in re.findall(r'this.a.e\[(\d+)\]',water)]
    assert terrain==[12,13,14]
    body=ab[ab.index('public final void b()'):ab.index('private void k()')]
    frames=[int(x) for x in re.findall(r'this.a.a.a\(\(\(k\)this.a\).a, (\d+), this.a, this.b\);',body)]
    assert len(frames)==20
    layers={'left':[frames[0:5],frames[5:10]],'right':[frames[10:15],frames[15:20]]}
    clothes=ab[ab.index('private void k()'):ab.index('public final void c()')]
    assert 'case 103:' not in clothes and 'case 99:' in clothes and 'case 114:' in clothes
    # Each branch uses the opposite side's first two shirt/body frames; hats keep frame0/1 offsets.
    keys=[int(x) for x in re.findall(r'this.a.a.a\(\(\(k\)this.a\).a, (\d+),',clothes)]
    assert len(keys)==32
    clothing={'left':[dict(zip([99,100,101,102,111,112,113,114],keys[i:i+8])) for i in [0,8]],
              'right':[dict(zip([99,100,101,102,111,112,113,114],keys[i:i+8])) for i in [16,24]]}
    island=json.loads((ROOT/'public/assets/maps/island.json').read_text())
    locations=[i for i,v in enumerate(island['layers']['Objects']) if v==85]
    assert len(locations)==1
    rules={'source':'data.a.c/A/B/b/G; data.ad.u/v; data.ab.b/k/c; data.g.b/n; data.t',
           'brokenItem':84,'item':94,'brokenMapId':85,'mapId':95,'index':locations[0],
           'waterTerrain':terrain,'boardingTiles':1,'landPriority':['left','right','up','down'],
           'strokePhases':7,'firstPosePhases':3,'sourcePixelsPerStroke':8,
           'layers':layers,'clothing':clothing}
    atlas=json.loads((ROOT/'public/assets/ui/atlas.json').read_text())
    for key in frames+keys: assert atlas['sheets'][key>>16]['frames'][key&65535]
    (ROOT/'src/game/data/raftRules.ts').write_text('// Generated by tools/recover_raft.py. Original raft evidence, no guessed frames.\nexport const raftRules = '+json.dumps(rules,indent=2)+' as const;\n')
    (ROOT/'evidence/raft-rules.json').write_text(json.dumps(rules,indent=2)+'\n')
    print('Recovered swamp-raft transitions, exact layers/outfits and landing predicate quirk.')
if __name__=='__main__': recover()

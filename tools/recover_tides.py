"""Verify original tide bands and remapping, preserving raw archive layers."""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[1]
def recover():
    g=(ROOT/'evidence/decompiled/data/g.java').read_text()
    body=g[g.index('public final void a(boolean bl)'):g.index('public final void j()')]
    maps={}
    for field in ['k','i']:
        pairs=re.findall(r'if \(this.a.'+field+r'\[n2\] == (\d+)\) \{\s*this.a.'+field+r'\[n2\] = (\d+);',body)
        maps[field]={int(a):int(b) for a,b in pairs}
    assert maps['k']=={4:0,5:4,6:5}
    assert maps['i']=={7:0,19:7,22:19,6:0,18:6,21:18,5:0,17:5,20:17}
    ad=(ROOT/'evidence/decompiled/data/ad.java').read_text()
    p=ad[ad.index('public final void p()'):ad.index('public final void q()')]
    bands=[list(map(int,m)) for m in re.findall(r'this.a.J >= (\d+)L && this.a.J <= (\d+)L',p)]
    assert bands==[[0,5],[12,17],[24,29],[36,41],[48,53],[6,11],[18,23],[30,35],[42,47],[54,59]]
    r=ad[ad.index('public final void r()'):ad.index('private void a(l[]')]
    assert 'while (n4 < 15)' in r and 'this.a.Z > 169 && this.a.Z < 176 && this.a.aa > 104 && this.a.aa < 113' in r
    assert 'this.a.aa = 101;' in r and 'this.a.Z = 166;' in r
    assert 'this.a.a.a(n6, n5) == 4' in r
    x=ad[ad.index('private void x()'):ad.index('public final void s()')]
    assert 'while (n3 < 10)' in x and 'while (n4 < 10)' in x
    rules={'source':'data.ad.p/r/x; data.g.a(boolean); data.aa.d; JVM descriptors p.r:Z,p.J:J',
      'bandMinutes':6,'cycleMinutes':12,'lowTerrain':maps['k'],'lowBorders':maps['i'],
      'rescueRadius':14,'rescueTerrain':4,'specialRescue':{'minX':170,'maxX':175,'minY':105,'maxY':112,'x':166,'y':101},
      'sharkSearch':10}
    (ROOT/'src/game/data/tideRules.ts').write_text('// Generated by tools/recover_tides.py. Source tide remaps and timing.\nexport const tideRules = '+json.dumps(rules,indent=2)+' as const;\n')
    (ROOT/'evidence/tide-rules.json').write_text(json.dumps(rules,indent=2)+'\n')
    print('Recovered six-minute tides, three terrain/nine border remaps and flood recovery rules.')
if __name__=='__main__': recover()

"""Recover s.k's huntable profiles and constructor arrow regions; keep source quirks."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def recover():
    source=(ROOT/'evidence/decompiled/data/s.java').read_text()
    method=source[source.index('private void k()'):source.index('public final void d()')]
    profiles=[]
    for item,body in re.findall(r'case (\d+): \{(.*?)(?=\n                case |\n            \})',method,re.S):
        frames={name:[int(v) for v in re.findall(r'this\.'+field+r'\[n2\]\[\d\] = (\d+);',body)] for name,field in [('right','a'),('left','b'),('idle','c')]}
        assert all(len(v)==2 for v in frames.values()),item
        vals={name:int(re.search(r'this\.'+field+r'\[n2\] = (\d+);',body)[1]) for name,field in [('width','k'),('height','l'),('speedY','g'),('speedX','h')]}
        profiles.append({'item':int(item),**frames,**vals,'dangerous':'this.a[n2] = true;' in body})
    assert len(profiles)==15 and 55 not in [p['item'] for p in profiles]
    bytecode=(ROOT/'evidence/bytecode/data.s.txt').read_text()
    ctor=bytecode[bytecode.index('public data.s(data.p);'):]
    body=re.search(r'newarray\s+int(.*?)putfield\s+#\d+\s+// Field a:\[I',ctor,re.S)[1]
    stack=[];values={}
    for op,arg in re.findall(r'^[ \t]*\d+:[ \t]+(iconst_\w+|bipush|sipush|ldc|iastore)[ \t]*([^\n]*)',body,re.M):
        if op=='iastore':
            value=stack.pop();index=stack.pop();values[index]=value
        elif op.startswith('iconst_'):stack.append(-1 if op=='iconst_m1' else int(op[7:]))
        elif op=='ldc':stack.append(int(re.search(r'// int (\d+)',arg)[1]))
        else:stack.append(int(arg.strip()))
    assert set(values)==set(range(6))
    arrows=[values[i] for i in range(6)]
    for marker in ['this.a.m[n2] == 45','this.k == 9','this.d[this.k] == 2','this.l += 4','this.a.n[81]','this.a.m[81]','this.a.D >= 1500L']:
        assert marker in source,marker
    rules={'source':'data.s.a/b/c/d/g/i/j/k, data.a.c/a(byte,int), javap data.s/p/v',
      'width':240,'height':320,'tickMs':90,'tool':81,'ammunition':45,'maxShots':10,'maxTargets':5,
      'attackMs':1500,'attackEnergy':{'42':50,'43':50,'48':10,'49':20},'protectedAttackEnergy':{'42':25,'43':25,'48':5,'49':10},
      'bowSprite':851990,'arrowFrames':arrows,'profiles':profiles}
    data=json.dumps(rules,indent=2)
    (ROOT/'evidence/hunting-rules.json').write_text(data+'\n')
    (ROOT/'src/game/data/huntingRules.ts').write_text('// Generated by tools/recover_hunting.py. 240x320 is a browser reference viewport.\nexport const huntingRules = '+data+' as const;\n')
    print('Recovered 15 hunting profiles, original hitboxes, danger flags and projectile regions. Shark is unsupported by s.k.')
if __name__=='__main__':recover()
